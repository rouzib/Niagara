"""Render measured Chrome trace intervals on a shared linear time axis."""

from __future__ import annotations

import json
import math
import textwrap
from collections.abc import Mapping, Sequence
from html import escape
from pathlib import Path
from typing import Any


class ExecutionTimeline:
    """Hold a standalone SVG of measured CPU and CUDA trace intervals.

    Parameters
    ----------
    svg : str
        SVG document generated by :func:`draw_timeline`.
    events : list of dict
        Selected trace intervals, with relative ``start_us``, ``duration_us``,
        ``device``, ``lane`` and original event ``name``.

    Attributes
    ----------
    svg : str
        Standalone SVG document.
    events : list of dict
        Measured intervals selected for this view.

    Notes
    -----
    The SVG has fixed, measured positions. Graphviz layout attributes do not
    apply. Hovering over an event shows its complete name and timing.
    """

    def __init__(self, svg: str, events: list[dict[str, Any]]) -> None:
        self.svg = svg
        self.events = events

    def pipe(self, format: str = "svg", *, encoding: str | None = None) -> bytes | str:
        """Return the SVG using the notebook-friendly Graphviz pipe convention.

        Parameters
        ----------
        format : str, optional
            Must be ``"svg"``. This renderer does not invoke Graphviz.
        encoding : str or None, optional
            Return text when provided; otherwise return UTF-8 bytes.

        Returns
        -------
        bytes or str
            Standalone SVG document.
        """
        if format != "svg":
            raise ValueError("ExecutionTimeline supports only format='svg'")
        data = self.svg.encode("utf-8")
        return data.decode(encoding) if encoding is not None else data

    def _repr_svg_(self) -> str:
        return self.svg


def draw_timeline(
    trace: str | Path | Mapping[str, Any],
    *,
    rankdir: str = "TB",
    time_size: float = 1000,
    lane_size: float = 180,
    devices: Sequence[str] | None = None,
    time_range: tuple[float, float] | None = None,
) -> ExecutionTimeline:
    """Draw measured execution intervals with position and extent set by time.

    Parameters
    ----------
    trace : str, pathlib.Path or mapping
        Chrome trace JSON exported by :func:`niagara.profile` or PyTorch's
        profiler, or its decoded dictionary containing ``traceEvents``.
        Chrome timestamps and durations are interpreted in microseconds.
    rankdir : {"TB", "LR"}, optional
        Time runs downward with duration represented by height, or left to
        right with duration represented by width. All lanes share one scale.
    time_size : float, optional
        Length of the time axis in SVG pixels.
    lane_size : float, optional
        Width of each device/thread lane for ``"TB"`` or height for ``"LR"``.
        Overlapping or nested intervals occupy separate tracks within a lane.
    devices : sequence of str or None, optional
        Keep only the listed devices, for example ``("cpu", "cuda:1")``.
        None shows CPU threads and all recorded GPU streams.
    time_range : pair of float or None, optional
        Visible start/end in microseconds relative to the first selected event.
        None shows the full interval. Partially visible events are clipped.

    Returns
    -------
    ExecutionTimeline
        SVG with measured event boxes, time ticks and timing tooltips. It can
        be displayed directly or through ``.pipe(format="svg")``.

    Notes
    -----
    CPU boxes are host operator intervals, including dispatch overhead and
    nested calls; they are not GPU execution durations. GPU boxes represent
    recorded kernels and memory transfers on their reported streams. Fusion
    and CUDA replay do not guarantee one event per captured FX node. No
    dependency edges or missing device timings are inferred from graph order.
    Profiling overhead can change the measured execution.
    """
    if rankdir not in ("TB", "LR"):
        raise ValueError("rankdir must be 'TB' or 'LR'")
    if not all(math.isfinite(v) and v > 0 for v in (time_size, lane_size)) or lane_size < 24:
        raise ValueError("time_size must be positive and lane_size must be at least 24; both must be finite")
    data = json.loads(Path(trace).read_text(encoding="utf-8")) if isinstance(trace, (str, Path)) else trace
    if not isinstance(data, Mapping) or not isinstance(data.get("traceEvents"), list):
        raise ValueError("Expected a Chrome trace containing a traceEvents list")
    selected = None if devices is None else set(devices)
    events = []
    for event in data["traceEvents"]:
        if not isinstance(event, Mapping) or event.get("ph") != "X":
            continue
        category = event.get("cat", "")
        if category not in ("cpu_op", "kernel", "gpu_memcpy", "gpu_memset"):
            continue
        try:
            start, duration = float(event["ts"]), float(event["dur"])
        except (KeyError, TypeError, ValueError):
            continue
        if not math.isfinite(start) or not math.isfinite(duration) or duration <= 0:
            continue
        args = event.get("args", {})
        args = args if isinstance(args, Mapping) else {}
        if category == "cpu_op":
            device = "cpu"
            lane = f"CPU · process {event.get('pid')} · thread {event.get('tid')}"
        else:
            device = f"cuda:{args['device']}" if "device" in args else f"gpu:{event.get('pid')}"
            track = f"stream {args['stream']}" if "stream" in args else f"track {event.get('tid')}"
            lane = f"{device} · {track}"
        if selected is None or device in selected:
            events.append({"name": str(event.get("name", "")), "category": category,
                           "device": device, "lane": lane, "start_us": start,
                           "duration_us": duration})
    if not events:
        raise ValueError("The trace has no measured operator, kernel or copy events for this selection")
    origin = min(event["start_us"] for event in events)
    for event in events:
        event["start_us"] -= origin
    start, stop = time_range or (0.0, max(e["start_us"] + e["duration_us"] for e in events))
    if not (math.isfinite(start) and math.isfinite(stop) and 0 <= start < stop):
        raise ValueError("time_range must have finite values with 0 <= start < end")
    events = [e for e in events if e["start_us"] < stop and e["start_us"] + e["duration_us"] > start]
    if not events:
        raise ValueError("The selected time_range contains no measured events")

    lanes = sorted({e["lane"] for e in events}, key=lambda lane: (not lane.startswith("CPU"), lane))
    tracks = {}
    for lane in lanes:
        ends = []
        for event in sorted((e for e in events if e["lane"] == lane), key=lambda e: (e["start_us"], -e["duration_us"])):
            track = next((i for i, end in enumerate(ends) if end <= event["start_us"]), len(ends))
            if track == len(ends):
                ends.append(0.0)
            ends[track] = event["start_us"] + event["duration_us"]
            event["track"] = track
        tracks[lane] = len(ends)

    left, bottom = 150.0, 60.0
    cross_size = lane_size * len(lanes)
    width = left + (cross_size if rankdir == "TB" else time_size) + 30
    notes = ["Host intervals include dispatch; CPU calls may be nested. GPU boxes are recorded kernels/copies.",
             "Box extent is proportional to duration; profiler overhead is included. Hover for names and timings."]
    if not any(e["device"] != "cpu" for e in events):
        notes.append("No GPU activity records in this selection.")
    lines = [line for note in notes for line in textwrap.wrap(note, width=max(24, int((width - 24) / 6)))]
    top = max(140.0, 50 + 14 * len(lines) + 45)
    height = top + (time_size if rankdir == "TB" else cross_size) + bottom
    scale = time_size / (stop - start)
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width:g}" height="{height:g}" viewBox="0 0 {width:g} {height:g}">',
             '<style>text{font-family:Arial,sans-serif;fill:#243746} .event{stroke:#52616b;stroke-width:.5} .tick{stroke:#dbe2e8;stroke-width:1}</style>',
             f'<rect width="{width:g}" height="{height:g}" fill="white"/>',
             '<text x="12" y="24" font-size="18">Measured execution</text>']
    for line, note in enumerate(lines):
        parts.append(f'<text x="12" y="{44+14*line:g}" font-size="11">{escape(note)}</text>')
    unit, divisor = ("ms", 1000.0) if stop - start >= 1000 else ("µs", 1.0)
    for index in range(6):
        value = start + (stop - start) * index / 5
        position = time_size * index / 5
        label = f"{value / divisor:.3g} {unit}"
        if rankdir == "TB":
            y = top + position
            parts += [f'<line class="tick" x1="{left:g}" y1="{y:g}" x2="{width-20:g}" y2="{y:g}"/>',
                      f'<text x="{left-8:g}" y="{y+4:g}" text-anchor="end" font-size="11">{label}</text>']
        else:
            x = left + position
            parts += [f'<line class="tick" x1="{x:g}" y1="{top:g}" x2="{x:g}" y2="{height-bottom:g}"/>',
                      f'<text x="{x:g}" y="{top-12:g}" text-anchor="middle" font-size="11">{label}</text>']
    for index, lane in enumerate(lanes):
        for line, label in enumerate(lane.split(" · ")):
            if rankdir == "TB":
                x, y = left + index * lane_size + 5, top - 42 + line * 14
            else:
                x, y = 8, top + index * lane_size + 16 + line * 14
            parts.append(f'<text x="{x:g}" y="{y:g}" font-size="10">{escape(label)}</text>')
    colors = {"cpu": "#e5e7eb", "cuda:0": "#b3d9f2", "cuda:1": "#ffce9e"}
    for event in events:
        visible_start = max(event["start_us"], start)
        visible_stop = min(event["start_us"] + event["duration_us"], stop)
        position = (visible_start - start) * scale
        extent = (visible_stop - visible_start) * scale
        track_size = (lane_size - 12) / tracks[event["lane"]]
        cross = lanes.index(event["lane"]) * lane_size + 6 + event["track"] * track_size
        if rankdir == "TB":
            x, y, w, h = left + cross, top + position, track_size * .94, extent
        else:
            x, y, w, h = left + position, top + cross, extent, track_size * .94
        color = "#a8dfbf" if event["category"] in ("gpu_memcpy", "gpu_memset") else colors.get(event["device"], "#d5d0eb")
        title = f"{event['name']}\n{event['lane']}\nstart {event['start_us']:.6g} µs; duration {event['duration_us']:.6g} µs"
        parts += [f'<g data-start-us="{event["start_us"]:.12g}" data-duration-us="{event["duration_us"]:.12g}" data-device="{escape(event["device"], quote=True)}">',
                  f'<title>{escape(title)}</title>',
                  f'<rect class="event" x="{x:.9g}" y="{y:.9g}" width="{max(w, 0):.9g}" height="{max(h, 0):.9g}" fill="{color}"/>']
        if w >= 40 and h >= 14:
            limit = max(3, int((w - 6) / 6))
            name = event["name"] if len(event["name"]) <= limit else event["name"][:limit-1] + "…"
            parts.append(f'<text x="{x+3:.9g}" y="{y+11:.9g}" font-size="10">{escape(name)}</text>')
        parts.append('</g>')
    parts.append('</svg>')
    return ExecutionTimeline("\n".join(parts), events)
